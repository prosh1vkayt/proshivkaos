/* gui/palette.h — единая таблица цветов, общая для всех архитектур.
 *
 * Переехала сюда из arch/x86/palette.h: она никогда и не была
 * x86-специфичной, просто раньше её единственным потребителем был
 * VGA DAC. На ARM64 аппаратной палитры не существует вообще (фреймбуфер
 * телефона — честный 32-битный RGB), поэтому индексы цветов превращаются
 * в настоящий RGB программно, прямо в gfxfb_present(). Таблица от этого
 * не меняется — меняется только то, кто её читает.
 *
 * Раскладка индексов:
 *    0..15  — классические 16 цветов VGA (совпадают с HAL_COLOR_* из hal.h)
 *   16..31  — цвета интерфейса в духе Windows XP + обоев (desktop-сборка)
 *   32..47  — базовая палитра тач-интерфейса (touch-сборка)
 *   48..71  — плавный градиент "планеты" на экране "о системе", 24 оттенка
 *   72..95  — дополнительные цвета тач-интерфейса: фон карточек-героев,
 *             сегменты диаграмм, вторичные акценты
 *   96..255 — свободны; в desktop-сборке туда грузится палитра запечённой
 *             картинки обоев (см. gui/wallpaper_data.h)
 */
#ifndef GUI_PALETTE_H
#define GUI_PALETTE_H

#include <stdint.h>

#define PALETTE_SIZE          256
#define PALETTE_FIXED_COLORS   96   /* сколько индексов занято под интерфейс */

typedef struct { uint8_t r, g, b; } palette_rgb_t;

/* Не const, в отличие от старой версии: индексы выше PALETTE_FIXED_COLORS
 * перепрограммируются на лету под картинку обоев. */
extern palette_rgb_t g_palette[PALETTE_SIZE];

/* Готовая таблица тех же цветов в формате 0x00RRGGBB — чтобы
 * gfxfb_present() на 32-битном фреймбуфере не пересчитывал их для
 * каждого из миллиона пикселей кадра. Обновляется вместе с g_palette. */
extern uint32_t g_palette_xrgb[PALETTE_SIZE];

void palette_init(void);

/* Задать диапазон цветов из массива троек R,G,B (обычные 0..255).
 * Обновляет обе таблицы разом. */
void palette_set_range(const uint8_t *rgb_255, int count, int start_index);

#endif
