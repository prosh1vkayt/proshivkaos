/* gui/touch/osk.h — экранная клавиатура.
 *
 * Без неё тач-сборка бессмысленна: на телефоне нет PS/2-порта, и терминал,
 * в который нечем набрать команду, — просто картинка. Это ровно тот пункт,
 * который в docs/ARM64_PLAN.md был отложен фразой "полноценный ввод с
 * тачскрина — отдельная большая задача".
 *
 * Клавиатура — обычный слой интерфейса, а не отдельная подсистема: она
 * получает те же события указателя, что и всё остальное, и возвращает
 * ASCII-символ, который затем идёт активному приложению так же, как если
 * бы он пришёл с физической клавиатуры через hal_input.
 */
#ifndef GUI_TOUCH_OSK_H
#define GUI_TOUCH_OSK_H

void osk_init(void);

/* Разместить клавиатуру: она всегда прижата к низу отведённой области. */
void osk_layout(int x, int y, int w);

/* Полная высота клавиатуры при текущих метриках — оболочка вычитает её из
 * области приложения, чтобы клавиатура ничего не перекрывала. */
int  osk_height(void);

void osk_render(void);

/* Обработка касания. type — одно из HAL_EV_POINTER_*.
 * Возвращает ASCII-код, если клавиша была НАЖАТА И ОТПУЩЕНА (символ
 * выдаётся по отпусканию, как на любой сенсорной клавиатуре: так можно
 * отвести палец в сторону и передумать), иначе 0. */
int  osk_handle_pointer(int type, int x, int y);

/* Попадает ли точка в область клавиатуры — оболочке нужно знать, чтобы не
 * отдать это касание приложению под ней. */
int  osk_contains(int x, int y);

void osk_set_visible(int visible);
int  osk_visible(void);

#endif
