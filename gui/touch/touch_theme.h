/* gui/touch/touch_theme.h — метрики и готовые элементы тач-интерфейса.
 *
 * Главное отличие от десктопной темы (gui/window.c): там все размеры —
 * жёсткие константы в пикселях (TITLE_BAR_H 10, TASKBAR_H 14), потому что
 * разрешений было ровно три и все известны заранее. Здесь так нельзя:
 * экран телефона может быть и 480x960, и 720x1440, и что угодно ещё, а
 * палец у пользователя во всех случаях одинаковый.
 *
 * Поэтому размеры считаются от разрешения экрана, а базовой единицей
 * служит не пиксель, а МИНИМАЛЬНАЯ ТАЧ-ЦЕЛЬ: элемент, в который человек
 * попадает пальцем не глядя. По всем гайдлайнам (Android, iOS, GNOME)
 * это примерно 7-9 мм; отсюда и пляшут остальные отступы.
 */
#ifndef GUI_TOUCH_THEME_H
#define GUI_TOUCH_THEME_H

#include "hal_gfx.h"

typedef struct {
    int screen_w, screen_h;

    int scale;        /* масштаб шрифта: 8x8 -> 8*scale x 8*scale     */
    int scale_small;  /* мелкий текст (статусбар, подписи иконок)     */
    int touch;        /* минимальная тач-цель, px                     */
    int pad;          /* базовый отступ                               */
    int gap;          /* просвет между элементами                     */
    int radius;       /* скругление карточек                          */

    int status_h;     /* высота статусбара сверху                     */
    int nav_h;        /* высота панели навигации снизу                */
    int icon;         /* сторона иконки приложения                    */
    int grid_cols;    /* колонок в сетке приложений                   */
} touch_metrics_t;

extern touch_metrics_t TM;

void touch_theme_init(int screen_w, int screen_h);

/* Область, доступная приложению: между статусбаром и навбаром. */
void touch_theme_content_rect(int *x, int *y, int *w, int *h);

/* ---- Готовые элементы ---- */

/* Обои: вертикальный градиент через дизеринг. Никаких запечённых картинок:
 * они нарисованы под landscape 4:3 и на портретном экране бесполезны. */
void touch_draw_wallpaper(void);

/* Карточка с тенью и скруглением — базовый контейнер интерфейса. */
void touch_draw_card(int x, int y, int w, int h, uint8_t color);

/* Кнопка. pressed меняет заливку — без визуального отклика на палец
 * интерфейс ощущается сломанным (палец закрывает то, во что тыкает).
 * Цвета задаются парой: раньше низ градиента был жёстко бирюзовым, и
 * ВЫКЛЮЧЕННЫЕ кнопки выглядели наполовину включёнными. */
void touch_draw_button(int x, int y, int w, int h, const char *label,
                        int pressed, uint8_t top, uint8_t bottom);

/* Иконка приложения: скруглённый квадрат с акцентным градиентом и
 * символом-глифом по центру, под ним подпись. */
void touch_draw_app_icon(int x, int y, int size, const char *glyph,
                          const char *label, uint8_t top, uint8_t bottom, int pressed);

/* Переключатель "вкл/выкл" для экрана настроек. */
void touch_draw_switch(int x, int y, int w, int h, int on);

/* Целое число в строку. Своей libc у нас нет, а печатать числа надо
 * повсюду: часы, аптайм, размеры файлов, разрешение экрана. buf должен
 * вмещать не меньше 12 байт. min_digits дополняет слева нулями (для часов
 * "09:05" вместо "9:5"). Возвращает buf. */
char *touch_itoa(int value, char *buf, int min_digits);

/* Дописать строку в конец буфера. Возвращает позицию нулевого байта. */
int   touch_strcat(char *dst, int pos, int max, const char *src);

/* Попадание точки в прямоугольник — тот же хит-тест, что и на десктопе. */
int  touch_hit(int px, int py, int rx, int ry, int rw, int rh);

/* Прямоугольник, расширенный до минимальной тач-цели: визуально кнопка
 * может быть маленькой, а зона нажатия обязана быть удобной. */
int  touch_hit_padded(int px, int py, int rx, int ry, int rw, int rh);

#endif
