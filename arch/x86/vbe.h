/* arch/x86/vbe.h — переключение разрешения через "Bochs VBE Extensions"
 * (порты 0x1CE/0x1CF). Этот интерфейс реализуют QEMU (std/stdvga), Bochs
 * и VirtualBox — на реальном железе его нет (это не настоящий VBE BIOS,
 * а виртуальный интерфейс эмулятора), поэтому режимы выше 320x200
 * работают только под эмуляцией. Для реального железа понадобился бы
 * либо настоящий VBE BIOS-вызов (нужен реальный/unreal режим), либо
 * vendor-specific программирование конкретного GPU — вне рамок этого
 * этапа.
 */
#ifndef ARCH_X86_VBE_H
#define ARCH_X86_VBE_H

#include <stdint.h>

/* Возвращает 1 при успехе (нашли VGA-устройство на PCI и включили режим),
 * 0 если что-то не найдено (например, запущено на реальном железе —
 * тогда стоит остаться на classic mode13h). out_lfb — физический адрес
 * линейного framebuffer'а (BAR0 видеокарты). */
int vbe_set_mode(uint16_t width, uint16_t height, uint8_t bpp, volatile uint8_t **out_lfb);

/* Выключить VBE-режим и вернуть видеокарту в состояние, где обычные VGA
 * регистры (см. vga13h.c) снова управляют выводом. ОБЯЗАТЕЛЬНО вызывать
 * перед переключением на classic mode13h после того, как был активен
 * VBE-режим — иначе видеокарта путает источник кадра (артефакты,
 * "повторы картинки" при возврате на низкое разрешение). */
void vbe_disable(void);

#endif
