/* arch/x86/rtc.h — чтение времени/даты из CMOS RTC (часы реального
 * времени на материнской плате, есть на любом x86, включая QEMU).
 * Не по прерываниям — опросный доступ к портам 0x70/0x71.
 */
#ifndef ARCH_X86_RTC_H
#define ARCH_X86_RTC_H

/* Текущие дата/время, все значения уже в обычной десятичной форме
 * (драйвер сам разбирает BCD, если CMOS в этом режиме). year — полный
 * (напр. 2026), month 1-12, hour 0-23. */
void rtc_read(int *year, int *month, int *day, int *hour, int *min, int *sec);

/* Только секунды (0-59) — дешёвая версия для отслеживания "тикнула ли
 * секунда" в цикле аптайма, не гоняет полное чтение всех регистров. */
int rtc_read_seconds(void);

/* Аптайм: вызывать rtc_uptime_tick() почаще (в главном цикле, каждую
 * итерацию) — она дёшево проверяет секундный регистр CMOS и инкрементит
 * счётчик при каждой смене. rtc_uptime_seconds() возвращает накопленное. */
void rtc_uptime_tick(void);
unsigned long rtc_uptime_seconds(void);

#endif
