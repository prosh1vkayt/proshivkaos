/* arch/arm64/uart_msm.c — драйвер UARTDM (Qualcomm), нужен для реальных
 * телефонов на Snapdragon: Redmi Note 4/4X (mido, MSM8953) и родственные.
 *
 * Почему нельзя обойтись PL011. Внешне обе микросхемы делают одно и то же —
 * гоняют байты по последовательному порту, — но регистры у них общего
 * ничего не имеют. У PL011 всё просто: положил байт в регистр данных, и он
 * уехал. UARTDM спроектирован вокруг передачи ПАКЕТАМИ через контроллер
 * DMA, поэтому перед каждой отправкой нужно ещё и объявить, сколько
 * символов сейчас будет передано (регистр NCF_TX).
 *
 * Откуда взяты смещения регистров. Это UARTDM версии 1.4 — та же ревизия
 * блока, что стоит на msm8916/msm8974/msm8953 и описана в U-Boot
 * (drivers/serial/serial_msm.c) и в ядре Linux (drivers/tty/serial/
 * msm_serial.c, таблица uartdm_regs). В device tree телефона этот блок
 * подписан "qcom,msm-lsuart-v14", а стоковая командная строка Android
 * содержит earlycon=msm_hsl_uart,0x78af000 — то есть адрес подтверждается
 * из двух независимых источников.
 *
 * Чего этот драйвер сознательно НЕ делает: не трогает тактирование и
 * скорость. К моменту, когда управление получаем мы, загрузчик уже
 * настроил и включил порт (он сам через него печатает свои логи), а
 * управление тактовыми частотами на Qualcomm — это отдельный драйвер GCC
 * с десятками регистров. Трогать рабочую настройку ради того, чтобы
 * выставить ту же самую скорость заново, — только повышать шанс всё
 * сломать.
 */
#include "arm64.h"

/* Смещения регистров UARTDM v1.4 */
#define UARTDM_DMEN     0x03C   /* режим DMA                              */
#define UARTDM_NCF_TX   0x040   /* сколько символов будет передано        */
#define UARTDM_RXFS     0x050   /* состояние приёмного FIFO               */
#define UARTDM_SR       0x0A4   /* статус                                 */
#define UARTDM_CR       0x0A8   /* команды и управление                   */
#define UARTDM_IMR      0x0B0   /* маска прерываний                       */
#define UARTDM_ISR      0x0B4   /* состояние прерываний                   */
#define UARTDM_TF       0x100   /* окно передачи (сюда пишем байты)       */
#define UARTDM_RF       0x140   /* окно приёма (отсюда читаем байты)      */

/* Биты регистра статуса */
#define SR_RX_READY     (1u << 0)   /* в приёмном FIFO есть данные        */
#define SR_TX_READY     (1u << 2)   /* можно писать в передающее окно     */
#define SR_TX_EMPTY     (1u << 3)   /* передатчик полностью опустошён     */

/* Команды регистра CR. Младшие биты — включение приёмника и передатчика,
 * старшие — одноразовые команды, которые сбрасывают состояние блока. */
#define CR_RX_ENABLE            (1u << 0)
#define CR_TX_ENABLE            (1u << 2)
#define CR_CMD_RESET_RX         (1u << 4)
#define CR_CMD_RESET_TX         (2u << 4)
#define CR_CMD_RESET_ERR        (3u << 4)
#define CR_CMD_RESET_TX_READY   (3u << 8)

static uint64_t g_base = 0;

/* Остаток слова, прочитанного из приёмного окна. UARTDM отдаёт приём по
 * четыре байта за раз, а наружу мы выдаём по одному — лишние держим здесь
 * до следующего вызова. */
static uint32_t g_rx_word = 0;
static int      g_rx_left = 0;

void msm_uart_init(uint64_t base) {
    g_base = base;

    /* Прерываниями не пользуемся — всё опрашивается в главном цикле. */
    mmio_write32(g_base + UARTDM_IMR, 0);

    /* Сбрасываем накопленные ошибки: загрузчик мог оставить взведённый
       флаг переполнения, и тогда приём молчал бы до сброса. */
    mmio_write32(g_base + UARTDM_CR, CR_CMD_RESET_ERR);

    /* Режим DMA выключаем: работаем через регистровые окна TF/RF. */
    mmio_write32(g_base + UARTDM_DMEN, 0);

    mmio_write32(g_base + UARTDM_CR, CR_TX_ENABLE | CR_RX_ENABLE);

    g_rx_left = 0;
}

void msm_uart_putc(char c) {
    if (!g_base) return;

    /* Терминалы ждут CR+LF, ядро печатает только LF. */
    if (c == '\n') msm_uart_putc('\r');

    /* Ждём, пока передатчик готов принять новую порцию. Счётчик-страховка:
       если порт настроен неверно или не тактируется, флаг не поднимется
       никогда, и без ограничения система молча зависла бы здесь навсегда —
       вместо того чтобы просто продолжить без вывода. */
    int guard = 100000;
    while (guard-- > 0) {
        uint32_t sr = mmio_read32(g_base + UARTDM_SR);
        if (sr & (SR_TX_EMPTY | SR_TX_READY)) break;
    }

    /* Объявляем длину пакета — один символ. Это и есть главное отличие от
       PL011: без записи в NCF_TX содержимое окна передачи не уедет. */
    mmio_write32(g_base + UARTDM_CR, CR_CMD_RESET_TX_READY);
    mmio_write32(g_base + UARTDM_NCF_TX, 1);
    (void)mmio_read32(g_base + UARTDM_NCF_TX);   /* обратное чтение упорядочивает запись */

    mmio_write32(g_base + UARTDM_TF, (uint32_t)(unsigned char)c);
}

int msm_uart_getc(void) {
    if (!g_base) return -1;

    /* Сначала отдаём то, что осталось от предыдущего слова. */
    if (g_rx_left > 0) {
        int c = (int)(g_rx_word & 0xFF);
        g_rx_word >>= 8;
        g_rx_left--;
        return c;
    }

    if (!(mmio_read32(g_base + UARTDM_SR) & SR_RX_READY))
        return -1;

    g_rx_word = mmio_read32(g_base + UARTDM_RF);
    g_rx_left = 4;

    /* ЧЕСТНАЯ ОГОВОРКА: полноценный приём на UARTDM требует работы с
       "устаревшими" событиями (stale interrupt) и счётчиком RX_TOTAL_SNAP —
       только они говорят, сколько байт в последнем неполном слове реально
       принято. Здесь этого нет, поэтому хвост пакета может дополняться
       нулями. Для нашей задачи приемлемо: последовательный порт на телефоне
       нужен прежде всего для ОТЛАДОЧНОГО ВЫВОДА, а ввод идёт с тачскрина.
       Нулевые байты отбрасываем — они же служат признаком пустоты. */
    int c = (int)(g_rx_word & 0xFF);
    g_rx_word >>= 8;
    g_rx_left--;
    return c ? c : -1;
}
