/* arch/arm64/reboot_msm.c — уйти в загрузчик по собственной воле.
 *
 * ЗАЧЕМ. Круг отладки на этом аппарате был такой: собрать образ,
 * загрузить его, дождаться, ВРУЧНУЮ вернуть телефон в загрузчик долгим
 * удержанием кнопок, поднять recovery, вычитать журнал. Ручной шаг
 * посередине означал, что круг не замкнуть — нужен человек у стола.
 *
 * Оказалось, что просить человека не обязательно. Загрузчик при старте
 * читает из служебной памяти на кристалле слово, объясняющее, зачем его
 * перезагрузили. Записав туда нужное значение и вызвав сброс, система
 * возвращается прямо в режим загрузчика — и tools/posdev забирает журнал
 * без чужой помощи.
 *
 * Значения взяты из исходников загрузчика для этого же процессора:
 *   MSM_SHARED_IMEM_BASE = 0x08600000, смещение признака 0x65C,
 *   FASTBOOT_MODE = 0x77665500.
 *
 * Сброс делаем сторожевым таймером: это единственный способ, доступный
 * без управления микросхемой питания. Ставим короткое время срабатывания
 * и разрешаем его — дальше он сделает всё сам. Область журнала при таком
 * сбросе сохраняется: ради этого она и заведена.
 */
#include "arm64.h"
#include "boards/board.h"

#ifdef BOARD_IMEM_RESTART_REASON

/* Смещения регистров сторожевого таймера — как в драйвере ядра. */
#define WDOG_RST        0x04
#define WDOG_EN         0x08
#define WDOG_BARK_TIME  0x10
#define WDOG_BITE_TIME  0x14

/* Время в тактах счётчика 32768 Гц. Четверти секунды с запасом хватает,
 * чтобы записанное успело дойти до памяти. */
#define BITE_TICKS      0x2000
#define BARK_TICKS      0x1000

void msm_reboot_bootloader(void) {
    /* Объясняем загрузчику, зачем его будят. */
    mmio_write32(BOARD_IMEM_RESTART_REASON, BOARD_REBOOT_BOOTLOADER);
    dsb_sy();

    /* И заводим сторожевой таймер на короткий срок. */
    mmio_write32(BOARD_WDOG_BASE + WDOG_RST, 1);
    mmio_write32(BOARD_WDOG_BASE + WDOG_BARK_TIME, BARK_TICKS);
    mmio_write32(BOARD_WDOG_BASE + WDOG_BITE_TIME, BITE_TICKS);
    mmio_write32(BOARD_WDOG_BASE + WDOG_EN, 1);
    dsb_sy();

    /* Ждём укуса. Возврата отсюда не бывает. */
    for (;;) __asm__ volatile ("wfi");
}

#endif
