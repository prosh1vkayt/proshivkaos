/* arch/arm64/boot.S — точка входа ядра на AArch64 (GNU as, не NASM:
 * NASM физически не умеет ARM, поэтому x86-шный boot/boot.asm тут не
 * переиспользуется — это его прямой аналог, см. docs/ARM64_PLAN.md п.1).
 *
 * Кто нас грузит:
 *   - QEMU  -M virt -kernel ...   (кладёт образ по RAM_BASE + text_offset)
 *   - LK / ABL / U-Boot на реальном телефоне из boot.img
 * Все трое понимают один и тот же формат — "ARM64 Linux Image", т.е.
 * сырой бинарник с 64-байтным заголовком в самом начале. Поэтому первая
 * инструкция обязана быть валидной веткой (загрузчик может просто прыгнуть
 * на начало образа, не разбирая заголовок), а сразу за ней идут поля
 * заголовка — их загрузчик читает как данные.
 *
 * Контракт ARM64 Boot Protocol на входе:
 *   x0 = физический адрес FDT (device tree blob)
 *   x1..x3 = 0 (зарезервированы)
 *   MMU выключен, D-кэш выключен, прерывания замаскированы,
 *   EL — обычно EL2 (QEMU virt с virtualization=on, реальные телефоны)
 *   или EL1 (QEMU virt по умолчанию). Обрабатываем оба случая.
 */

#if defined(CONFIG_LOG_RAMOOPS) || defined(CONFIG_EARLY_FB_MARKS)
/* Ради BOARD_PSTORE_CONSOLE_ADDR и параметров экрана. Заголовок платы состоит из одних
   #define, поэтому ассемблер его переваривает; boards/board.h — уже нет, он
   тянет за собой объявления на C. Возможность включается лишь на платах, у
   которых такая область есть, так что имя платы здесь не гадание. */
#include "boards/mido.h"
#endif

#ifdef CONFIG_EARLY_FB_MARKS
/* Высота полосы в строках экрана. Шестьдесят четыре — видно с другого
   конца комнаты, а закрашивается меньше чем за десятую долю секунды даже
   побайтно при выключенном кэше. */
#define EARLY_BAND_H      64
#define EARLY_BAND_BYTES  (BOARD_FB_STRIDE * EARLY_BAND_H)
#endif

.section ".text.boot", "ax"
.global _start

_start:
    /* ---------------- ARM64 Linux Image header (64 байта) ------------- */
    b       _boot                   /* code0: исполняемая ветка          */
    .long   0                       /* code1: зарезервировано            */
    .quad   0x80000                 /* text_offset: смещение от базы RAM */
    .quad   __image_size            /* image_size: полный размер образа  */
    .quad   0xA                     /* flags: LE + страницы 4 КиБ        */
    .quad   0                       /* res2                              */
    .quad   0                       /* res3                              */
    .quad   0                       /* res4                              */
    .long   0x644d5241              /* magic "ARM\x64"                   */
    .long   0                       /* res5: смещение PE/COFF-заголовка  */

_boot:
    /* x0 = DTB. Дальше x0 НЕ трогаем до самого вызова kmain. */

    /* Многоядерность: на этом этапе планировщика нет, поэтому все ядра
       кроме нулевого просто паркуем в wfi. MPIDR_EL1[7:0] = Aff0. */
    mrs     x1, mpidr_el1
    and     x1, x1, #0xFF
    cbnz    x1, _park

#ifdef CONFIG_LOG_RAMOOPS
    /* ---------------- Самая ранняя метка ------------------------------ */
    /*
     * Записывается ДО всего остального: до спуска из EL2, до перемещения
     * образа, до обнуления .bss и тем более до первой строки на C. Пишем
     * в область ОЗУ, которую телефон исключил из общего пула ради своего
     * посмертного журнала (см. arch/arm64/ramoops.c) — она переживает
     * перезагрузку, поэтому написанное читается уже из Android:
     *
     *     adb shell su -c 'cat /sys/fs/pstore/console-ramoops'
     *
     * Смысл именно в том, чтобы метка стояла раньше всего. Пока её нет,
     * "система упала на первой же инструкции" и "загрузчик до неё вообще
     * не доехал" выглядят с телефона одинаково — чёрный экран и обычная
     * загрузка Android. Появилась метка — значит, управление нам передали,
     * и разбираться надо в нашем коде. Не появилась — значит, до нас дело
     * не дошло, и искать надо в образе или в загрузчике.
     *
     * Заодно метка отвечает на два вопроса, которые иначе приходится
     * угадывать: по какому адресу нас на самом деле положили (загрузчик
     * телефона не обязан слушаться заголовка образа) и что лежит в x0 —
     * то есть передали ли нам дерево устройств вообще.
     *
     * MMU выключен, вся память трактуется как устройство, кэша нет —
     * записанное сразу оказывается в ОЗУ, выталкивать нечего.
     */
    movz    x10, #(BOARD_PSTORE_CONSOLE_ADDR & 0xFFFF)
    movk    x10, #(BOARD_PSTORE_CONSOLE_ADDR >> 16), lsl #16

    movz    w11, #0x4244                    /* сигнатура "DBGC", младшая  */
    movk    w11, #0x4347, lsl #16           /* половина и старшая         */
    str     w11, [x10]
    str     wzr, [x10, #4]                  /* курсор кольца: не крутилось */

    add     x12, x10, #12                   /* начало данных за заголовком */

    adr     x13, _msg_entry
    bl      _early_str

    mrs     x16, CurrentEL                  /* уровень, на котором стартовали */
    lsr     x16, x16, #2
    add     w15, w16, #'0'
    strb    w15, [x12], #1

    adr     x13, _msg_image
    bl      _early_str
    adr     x16, _start                     /* фактический адрес загрузки  */
    bl      _early_hex

    adr     x13, _msg_dtb
    bl      _early_str
    mov     x16, x0                         /* дерево устройств от загрузчика */
    bl      _early_hex

    mov     w15, #'\n'
    strb    w15, [x12], #1

    sub     w11, w12, w10                   /* длина = курсор минус начало */
    sub     w11, w11, #12                   /* за вычетом заголовка        */
    str     w11, [x10, #8]
#endif

#ifdef CONFIG_EARLY_FB_MARKS
    /* полоса 0, красная: управление получено */
    mov     x21, #0
    movz    w22, #255
    movz    w23, #0
    movz    w24, #0
    bl      _early_band
#endif

    /* ---------------- EL2 -> EL1 (если стартовали в EL2) -------------- */
    mrs     x1, CurrentEL
    lsr     x1, x1, #2
    cmp     x1, #2
    b.ne    _at_el1

    mov     x2, #1
    lsl     x2, x2, #31             /* HCR_EL2.RW = 1: EL1 работает в    */
    msr     hcr_el2, x2             /* AArch64, а не в AArch32           */

    mrs     x2, cnthctl_el2         /* EL1PCTEN|EL1PCEN: разрешить EL1   */
    orr     x2, x2, #3              /* читать системный счётчик — на нём */
    msr     cnthctl_el2, x2         /* держится весь hal_time_ms()       */
    msr     cntvoff_el2, xzr

    mov     x2, #0x0800             /* SCTLR_EL1 в состояние "после      */
    movk    x2, #0x30d0, lsl #16    /* сброса": MMU и кэши выключены     */
    msr     sctlr_el1, x2

    mov     x2, #0x3c5              /* SPSR_EL2 = EL1h, DAIF замаскирован */
    msr     spsr_el2, x2
    adr     x2, _at_el1
    msr     elr_el2, x2
    eret                            /* спуск в EL1, продолжаем с _at_el1 */

_at_el1:
    /* ---------------- Перемещение образа по фактическому адресу ------- */
    /*
     * Загрузчик телефона кладёт ядро туда, куда считает нужным, и это НЕ
     * тот адрес, на который образ слинкован. Инструкции от этого не
     * страдают: adrp/add считают адрес относительно счётчика команд. А вот
     * указатели, лежащие в данных, — страдают. Таблица приложений, строки,
     * массивы указателей на функции: всё это компоновщик заполнил
     * абсолютными адресами. В нашем образе таких мест больше трёхсот, и
     * каждое из них при загрузке по другому адресу превращается в мусор.
     * Обращение по первому же такому указателю — и система падает, не успев
     * ничего сообщить.
     *
     * Поэтому образ собирается позиционно-независимым: компоновщик
     * складывает все такие места в таблицу .rela.dyn, а мы проходим её и
     * прибавляем к каждому значению смещение "куда нас положили минус куда
     * слинковали". Ровно так же поступает ядро Linux на этой архитектуре.
     *
     * Делать это надо ДО любого обращения к данным — то есть до обнуления
     * .bss и тем более до вызова C.
     */
    ldr     x2, =_start             /* адрес, на который слинкованы */
    adr     x3, _start              /* адрес, по которому реально лежим */
    subs    x28, x3, x2             /* смещение; ноль — правки не нужны  */
    b.eq    _relocated

    adrp    x4, __rela_start
    add     x4, x4, :lo12:__rela_start
    adrp    x5, __rela_end
    add     x5, x5, :lo12:__rela_end

_reloc_loop:
    cmp     x4, x5
    b.hs    _relocated

    /* Elf64_Rela: смещение (8) + тип (8) + добавка (8) */
    ldp     x6, x7, [x4], #16
    ldr     x8, [x4], #8

    /* Интересует единственный тип — R_AARCH64_RELATIVE (1027). Других в
       статически слинкованном PIE и не бывает; всё прочее пропускаем. */
    mov     x9, #1027
    cmp     x7, x9
    b.ne    _reloc_loop

    add     x6, x6, x28             /* куда писать: адрес с поправкой  */
    add     x8, x8, x28             /* что писать: значение с поправкой */
    str     x8, [x6]
    b       _reloc_loop

_relocated:
#ifdef CONFIG_EARLY_FB_MARKS
    /* полоса 1, зелёная: образ перемещён по фактическому адресу */
    mov     x21, #1
    movz    w22, #0
    movz    w23, #255
    movz    w24, #0
    bl      _early_band
#endif

    /* ---------------- Стек ------------------------------------------- */
    /* Аналог "mov esp, stack_top" из x86-шного boot.asm. adrp+add вместо
       ldr =symbol: не нужен литерал-пул и образ остаётся позиционно
       корректным при загрузке по адресу из линкер-скрипта. */
    adrp    x1, __stack_top
    add     x1, x1, :lo12:__stack_top
    mov     sp, x1

    /* ---------------- Обнуление .bss ---------------------------------- */
    /* На x86 это делал GRUB (Multiboot гарантирует обнулённый .bss).
       Здесь никто за нас этого не делает: загрузчик кладёт в память ровно
       столько байт, сколько занимает файл образа, а .bss в файле не
       хранится вообще. Без обнуления hal_mem, RamFS и вся статика ядра
       стартуют с мусором. */
    adrp    x1, __bss_start
    add     x1, x1, :lo12:__bss_start
    adrp    x2, __bss_end
    add     x2, x2, :lo12:__bss_end
1:  cmp     x1, x2
    b.hs    2f
    str     xzr, [x1], #8
    b       1b
2:
#ifdef CONFIG_EARLY_FB_MARKS
    /* полоса 2, синяя: .bss обнулён, стек поставлен */
    mov     x21, #2
    movz    w22, #0
    movz    w23, #96
    movz    w24, #255
    bl      _early_band
#endif

    /* ---------------- Таблица векторов исключений --------------------- */
    adrp    x1, _vectors
    add     x1, x1, :lo12:_vectors
    msr     vbar_el1, x1
    isb

    /* ---------------- kmain(magic, boot_info) ------------------------- */
    /* Сигнатура kmain() общая с x86, менять её не нужно: там, где на x86
       лежит указатель на multiboot_info, здесь лежит указатель на DTB.
       magic передаём нулевой — ядро его и так игнорирует. */

#ifdef CONFIG_EARLY_FB_MARKS
    /* полоса 3, белая: уходим в C */
    mov     x21, #3
    movz    w22, #255
    movz    w23, #255
    movz    w24, #255
    bl      _early_band
#endif
    mov     x1, x0                  /* arg1 = DTB   */
    mov     x0, #0                  /* arg0 = magic */
    bl      kmain

_park:
    wfi
    b       _park

#ifdef CONFIG_EARLY_FB_MARKS
/* ---------------- Полосы на экране ------------------------------------
 *
 * Закрасить полосу во весь экран. Номер полосы в x21, цвет побайтно в
 * w22/w23/w24 (красный, зелёный, синий).
 *
 * Экран трогаем напрямую, потому что загрузчик уже настроил дисплей ради
 * своего логотипа и оставил его работающим. Формат — три байта на пиксель,
 * строки уложены вплотную, так что полоса это просто непрерывный кусок
 * памяти: шаг строки, умноженный на высоту полосы.
 *
 * Стека здесь ещё нет, поэтому подпрограмма не сохраняет ничего и портит
 * только x25-x27. x0 (дерево устройств) не трогаем принципиально.
 */
_early_band:
    movz    x25, #(BOARD_FB_ADDR & 0xFFFF)
    movk    x25, #(BOARD_FB_ADDR >> 16), lsl #16
    movz    x26, #(EARLY_BAND_BYTES & 0xFFFF)
    movk    x26, #(EARLY_BAND_BYTES >> 16), lsl #16
    mul     x27, x21, x26
    add     x25, x25, x27
1:  strb    w22, [x25], #1
    strb    w23, [x25], #1
    strb    w24, [x25], #1
    subs    x26, x26, #3
    b.gt    1b
    ret
#endif

#ifdef CONFIG_LOG_RAMOOPS
/* ---------------- Вспомогательное для ранней метки --------------------
 *
 * Обе подпрограммы пишут по курсору x12 и двигают его. Соглашений о
 * вызовах не соблюдают и не должны: работают до появления стека, кроме
 * x30 ничего не трогают, друг друга не вызывают.
 */

/* Скопировать строку из x13 до нулевого байта. */
_early_str:
1:  ldrb    w15, [x13], #1
    cbz     w15, 2f
    strb    w15, [x12], #1
    b       1b
2:  ret

/* Написать x16 шестнадцатерично, все 16 цифр — ведущие нули оставляем:
   так адреса выстраиваются в столбик и разница видна с одного взгляда. */
_early_hex:
    mov     x17, #60
1:  lsr     x19, x16, x17
    and     x19, x19, #0xF
    cmp     x19, #10
    b.lo    2f
    add     x19, x19, #('a' - 10)
    b       3f
2:  add     x19, x19, #'0'
3:  strb    w19, [x12], #1
    subs    x17, x17, #4
    b.ge    1b
    ret

_msg_entry: .asciz  "\n[proshivkaOS] boot.S: upravlenie polucheno, EL="
_msg_image: .asciz  " obraz=0x"
_msg_dtb:   .asciz  " dtb=0x"
    .align  2
#endif
