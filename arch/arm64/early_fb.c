/* arch/arm64/early_fb.c — полосы на экране как единственный отладочный вывод.
 *
 * Продолжение того, что делает boot.S, но уже из C. Смысл тот же: на этом
 * телефоне отладочный порт выведен на разъём наушников и требует паяного
 * кабеля, область журнала без root не прочитать, а команды выгрузки у
 * стокового загрузчика нет. Остаётся экран — загрузчик настроил дисплей
 * ради своего логотипа и оставил его работающим.
 *
 * Полосы идут сверху вниз, по одной на этап. Сколько успело появиться, до
 * того места и дошло. Фотографии экрана достаточно, чтобы назвать этап, —
 * а это ровно то, чего не хватало: без них "не запустилось" и
 * "запустилось и упало" выглядят одинаково.
 *
 * ПОРЯДОК БАЙТОВ. Три байта на пиксель, и лежат они СИНИЙ, зелёный,
 * красный — обратно названию формата "r8g8b8". Название перечисляет
 * разряды значения от старшего к младшему, а при обратном порядке байтов
 * старший ложится последним. Выяснилось это на живом устройстве: полосы,
 * закрашенные как R,G,B, вышли с перепутанными синей и красной. Здесь
 * функция принимает цвет по-человечески, а раскладывает правильно.
 */
#include "arm64.h"
#include "boards/board.h"

#ifdef CONFIG_EARLY_FB_MARKS

#define BAND_H 64

void early_fb_band(int index, uint8_t r, uint8_t g, uint8_t b) {
    if (index < 0) return;

    /* За нижний край экрана не вылезаем: там уже чужая память. */
    long first_row = (long)index * BAND_H;
    if (first_row + BAND_H > BOARD_FB_HEIGHT) return;

    volatile uint8_t *p = (volatile uint8_t *)(uintptr_t)BOARD_FB_ADDR
                        + first_row * BOARD_FB_STRIDE;

    long bytes = (long)BOARD_FB_STRIDE * BAND_H;
    for (long i = 0; i + 2 < bytes; i += 3) {
        p[i + 0] = b;
        p[i + 1] = g;
        p[i + 2] = r;
    }

    /* Выталкивать в ОЗУ больше не нужно: кадр размечен как память
       устройств (см. arch/arm64/mmu.c), запись попадает туда сразу.
       Раньше здесь стоял сброс кэша, и он же был первым таким сбросом за
       всю загрузку — до включения MMU эта ветка пропускалась. Убрав
       кэширование кадра, мы убрали и необходимость его обслуживать. */
}

#endif /* CONFIG_EARLY_FB_MARKS */
