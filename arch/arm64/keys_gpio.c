/* arch/arm64/keys_gpio.c — аппаратные клавиши, висящие на выводах TLMM.
 *
 * На этом телефоне так подключена только одна клавиша — увеличение
 * громкости. Остальные (питание и уменьшение громкости) заведены на
 * микросхему питания и доступны через шину SPMI, а это отдельный драйвер.
 *
 * Номер вывода снят с дерева прошивки, а не подобран:
 *
 *     gpio_keys { vol_up { gpios = <&tlmm 85 1>; linux,code = <115>; } }
 *
 * Единица в третьем поле означает "активна низким уровнем": в покое
 * подтяжка держит на выводе единицу, нажатие сажает его в ноль.
 *
 * ЗАЧЕМ ОДНА КЛАВИША НУЖНА. Пока тачскрин не поднят, управлять системой
 * нечем вообще: экран рисуется, но ни одно нажатие никуда не идёт.
 * Одной клавиши хватает, чтобы обойти интерфейс целиком — см. обработчик
 * в gui/touch/touch_ui.c, где она работает как "назад" внутри приложения
 * и как переключатель приложений на рабочем столе.
 */
#include "arm64.h"
#include "boards/board.h"
#include "hal_time.h"

#ifdef BOARD_KEY_VOLUP_GPIO

/* Дребезг контакта: механическая клавиша при нажатии несколько раз
 * замыкается и размыкается за единицы миллисекунд. Без выдержки одно
 * нажатие превратилось бы в десяток. Пятнадцать миллисекунд — то же
 * значение, что стоит в дереве прошивки (debounce-interval). */
#define DEBOUNCE_MS  15

static int      g_ready    = 0;
static int      g_pressed  = 0;   /* последнее устойчивое состояние */
static uint64_t g_settle   = 0;   /* до этого момента изменения не верим */

int keys_gpio_init(void) {
    /* Вход с подтяжкой вверх: клавиша активна низким уровнем, и в покое
       линию должно что-то удерживать в единице. */
    tlmm_gpio_input(BOARD_KEY_VOLUP_GPIO, 1);
    g_pressed = 0;
    g_settle  = 0;
    g_ready   = 1;
    return 1;
}

/* Опрос. Возвращает 1 и заполняет down, если состояние клавиши
 * изменилось, иначе 0. */
int keys_gpio_poll(int *down) {
    if (!g_ready) return 0;

    uint64_t now = hal_time_ms();
    if (now < g_settle) return 0;

    int level = tlmm_gpio_get(BOARD_KEY_VOLUP_GPIO);
    int pressed = !level;               /* активна низким уровнем */

    if (pressed == g_pressed) return 0;

    g_pressed = pressed;
    g_settle  = now + DEBOUNCE_MS;
    *down = pressed;
    return 1;
}

#endif /* BOARD_KEY_VOLUP_GPIO */
