/* arch/arm64/platform.h — что мы знаем о железе, на котором запустились.
 *
 * Одно место, где сходятся два источника сведений о плате:
 *   1. device tree от загрузчика — главный, работает на любом устройстве;
 *   2. константы из заголовков arch/arm64/boards — запасной, если
 *      дерева нет или в нём нет нужного узла.
 *
 * Всё остальное ядро смотрит только сюда и не знает, откуда взялся адрес.
 */
#ifndef ARCH_ARM64_PLATFORM_H
#define ARCH_ARM64_PLATFORM_H

#include <stdint.h>

/* Какой контроллер последовательного порта стоит на плате. */
enum {
    UART_KIND_NONE = 0,
    UART_KIND_PL011,      /* ARM PrimeCell — QEMU virt и большинство плат  */
    UART_KIND_MSM         /* Qualcomm UARTDM — телефоны на Snapdragon      */
};

typedef struct {
    /* Откуда получены сведения: 1 — device tree разобран, 0 — только
     * константы платы. Полезно видеть на экране "о системе": сразу ясно,
     * читает система железо или работает по зашитым адресам. */
    int fdt_ok;
    const char *model;        /* строка model из дерева либо имя платы     */

    int      uart_kind;
    uint64_t uart_base;
    int      uart_from_fdt;   /* адрес взят из дерева, а не из константы   */

    uint64_t gic_base;        /* контроллер прерываний; 0 — не найден.
                               * Пока только обнаруживается: прерывания в
                               * системе не используются, всё опрашивается
                               * в цикле. Нужен будет вместе с планировщиком. */

    /* Готовый фреймбуфер, оставленный загрузчиком (узел simple-framebuffer).
     * valid = 0 означает "в дереве такого нет" — тогда графика идёт либо
     * через ramfb под QEMU, либо по константам платы. */
    int      fb_valid;
    uint64_t fb_addr;
    int      fb_width, fb_height, fb_stride;
    int      fb_format;       /* значение GFXFB_FMT_*                      */
} platform_info_t;

/* Разобрать device tree и заполнить сведения. Вызывается самой первой, до
 * MMU и до вывода: пока платформа не определена, печатать всё равно некуда.
 * Указатель может быть нулевым или мусорным — функция это переживёт. */
void platform_probe(const void *dtb);

const platform_info_t *platform(void);

#endif
