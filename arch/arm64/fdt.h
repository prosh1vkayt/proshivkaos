/* arch/arm64/fdt.h — минимальный разбор Flattened Device Tree.
 *
 * Зачем. До сих пор все адреса периферии были захардкожены: сначала прямо
 * в arm64.h под QEMU virt, потом в заголовках arch/arm64/boards под конкретные
 * платы. Это тупик — на каждый новый телефон пришлось бы заводить новый
 * заголовок и пересобирать образ.
 *
 * Между тем загрузчик УЖЕ передаёт нам полное описание железа: указатель
 * на device tree лежит в регистре x0, boot.S доносит его до kmain()
 * (см. ARM64 Boot Protocol). Там перечислены и адреса UART, и контроллер
 * прерываний, и — если повезёт — готовый фреймбуфер. Этот файл достаёт их
 * оттуда.
 *
 * Что реализовано и чего сознательно нет. Полноценная libfdt — это тысячи
 * строк с поддержкой изменения дерева, phandle-ссылок и склейки оверлеев.
 * Нам нужно только читать, поэтому здесь ровно четыре операции: найти узел
 * по compatible, найти узел по пути, прочитать свойство, разобрать reg.
 * Ни одной аллокации: дерево читается на месте, прямо из памяти
 * загрузчика.
 *
 * ВАЖНО про выравнивание. Разбор происходит ДО включения MMU, когда вся
 * память трактуется как Device-nGnRnE и невыровненное обращение —
 * гарантированный abort. Поэтому все многобайтные значения собираются из
 * отдельных байтов (см. be32() в fdt.c), а не читаются как uint32_t.
 * Заодно это решает вопрос порядка байт: device tree всегда big-endian,
 * независимо от процессора.
 */
#ifndef ARCH_ARM64_FDT_H
#define ARCH_ARM64_FDT_H

#include <stdint.h>

/* Найденный узел. Хранит не только своё положение, но и разрядности
 * адреса/размера, объявленные РОДИТЕЛЕМ: именно ими кодируется свойство
 * reg этого узла. На реальных платах это принципиально — например, в
 * дереве Redmi Note 4 корень объявляет двухсловные адреса, а шина /soc
 * внутри себя переходит на однословные. */
typedef struct {
    uint32_t props_off;    /* смещение первого свойства в struct-блоке */
    uint8_t  addr_cells;   /* #address-cells РОДИТЕЛЯ                   */
    uint8_t  size_cells;   /* #size-cells РОДИТЕЛЯ                      */
} fdt_node_t;

/* Проверяет сигнатуру и запоминает блоб. 1 — дерево пригодно к разбору.
 * Указатель может быть нулевым или мусорным (так бывает, если загрузчик
 * ничего не передал) — функция это переживает и возвращает 0. */
int fdt_init(const void *blob);
int fdt_valid(void);

/* Строка model из корня дерева ("Qualcomm Technologies, Inc. APQ8053 MTP")
 * или 0. Полезна для отладочного вывода: сразу видно, что за железо. */
const char *fdt_model(void);

/* Первый узел, у которого в списке compatible есть указанная строка.
 * Сравнение точное и по каждой строке списка отдельно. */
int fdt_find_compatible(const char *compat, fdt_node_t *out);

/* Узел по абсолютному пути вида "/soc/serial@78af000". Компонент пути
 * совпадает либо целиком, либо по части до '@' — так принято в спецификации
 * (в stdout-path имя пишут с адресом, в ссылках нередко без). */
int fdt_path(const char *path, fdt_node_t *out);

/* Сырое свойство. len можно передать нулём, если длина не нужна. */
const void *fdt_prop(const fdt_node_t *node, const char *name, uint32_t *len);

/* Свойство-число (одно 32-битное слово) и свойство-строка. */
int fdt_prop_u32(const fdt_node_t *node, const char *name, uint32_t *out);
const char *fdt_prop_str(const fdt_node_t *node, const char *name);

/* index-я пара (адрес, размер) из свойства reg, уже собранная в 64 бита с
 * учётом разрядностей родителя. size можно передать нулём. */
int fdt_reg(const fdt_node_t *node, int index, uint64_t *addr, uint64_t *size);

#endif
