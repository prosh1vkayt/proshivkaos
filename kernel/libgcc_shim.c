/*
 * libgcc_shim.c — свои __udivdi3/__umoddi3/__divdi3/__moddi3 для 32-битного x86.
 *
 * У 32-битного x86 нет инструкции деления 64-битных чисел, поэтому компилятор
 * САМ вставляет вызовы этих функций для любого "uint64_t / uint64_t" (или %).
 * В обычной пользовательской программе их даёт libgcc, которую подтягивает
 * линковщик. У нас же нет гарантии, что на машине, где идёт сборка, стоит
 * настоящий 32-битный кросс-компилятор (i686-elf-gcc): если его нет и CC
 * откатывается на хостовый gcc -m32, libgcc может оказаться не той разрядности
 * (см. Makefile) — линковщик молча пропустит несовместимый архив, и сборка
 * упадёт с "undefined reference to __udivdi3" уже на этапе линковки ядра.
 *
 * Раз от системного libgcc для этой пары функций всё равно нельзя надёжно
 * зависеть, надёжнее не зависеть от него вовсе: пара десятков строк простого
 * битового деления работает одинаково на любом тулчейне.
 *
 * На ARM64 такой проблемы нет — там 64-битное деление есть аппаратно, и
 * aarch64-elf-gcc/aarch64-none-elf-gcc это полноценный bare-metal
 * кросс-компилятор со своей корректной libgcc. Поэтому файл компилируется
 * только под i386/x86 — на arm64 в нём просто ничего нет.
 */

#if defined(__i386__) && !defined(__x86_64__)

#include <stdint.h>

/* Беззнаковое деление: обычный битовый (school-book) алгоритм.
 * num/den — 64-битные, работаем по одному биту частного за раз. */
uint64_t __udivdi3(uint64_t num, uint64_t den)
{
    if (den == 0) {
        /* Деление на ноль в ядре — программная ошибка, а не то, что можно
         * тихо "поправить" произвольным числом. 0 — не более честный
         * результат, чем любой другой, но хотя бы не роняет сборку. */
        return 0;
    }

    uint64_t quot = 0;
    uint64_t rem  = 0;

    for (int i = 63; i >= 0; i--) {
        rem <<= 1;
        rem |= (num >> i) & 1ULL;
        if (rem >= den) {
            rem -= den;
            quot |= (1ULL << i);
        }
    }

    return quot;
}

uint64_t __umoddi3(uint64_t num, uint64_t den)
{
    if (den == 0) {
        return 0;
    }
    uint64_t q = __udivdi3(num, den);
    return num - q * den;
}

/* Знаковые варианты — через беззнаковые, с учётом знака отдельно. */
int64_t __divdi3(int64_t num, int64_t den)
{
    int neg = 0;
    uint64_t a, b;

    if (num < 0) { a = (uint64_t)(-num); neg = !neg; } else { a = (uint64_t)num; }
    if (den < 0) { b = (uint64_t)(-den); neg = !neg; } else { b = (uint64_t)den; }

    uint64_t q = __udivdi3(a, b);
    return neg ? -(int64_t)q : (int64_t)q;
}

int64_t __moddi3(int64_t num, int64_t den)
{
    int64_t q = __divdi3(num, den);
    return num - q * den;
}

#endif /* __i386__ && !__x86_64__ */
