/* hal/hal_input.h — единая модель ввода для ВСЕХ устройств ввода.
 *
 * Зачем это вместо прямых вызовов mouse_poll()/keyboard_poll(): на x86 у нас
 * PS/2-мышь, которая шлёт ОТНОСИТЕЛЬНЫЕ смещения (dx/dy), а на телефоне —
 * тачскрин, который шлёт АБСОЛЮТНУЮ точку касания и не имеет курсора вообще.
 * Оконный менеджер не должен знать разницы: он хочет "палец/курсор нажали
 * вот сюда", "провели туда", "отпустили". Поэтому HAL приводит оба источника
 * к одной модели указателя (pointer), а x86-бэкенд сам ведёт положение
 * курсора и превращает относительные дельты в абсолютные координаты.
 *
 * Ключевой инвариант тот же, что и у остального HAL: gui/ и kernel/ не
 * содержат ни одного #ifdef по архитектуре — только hal_input_*.
 */
#ifndef PROSHIVKAOS_HAL_INPUT_H
#define PROSHIVKAOS_HAL_INPUT_H

#include <stdint.h>

enum {
    HAL_EV_NONE = 0,
    HAL_EV_KEY,            /* нажата клавиша (физическая или экранная) — .key */
    HAL_EV_POINTER_DOWN,   /* палец коснулся / кнопка мыши нажата — .x/.y     */
    HAL_EV_POINTER_MOVE,   /* палец ведут / курсор двигают — .x/.y, .pressed  */
    HAL_EV_POINTER_UP      /* палец подняли / кнопку отпустили — .x/.y        */
};

typedef struct {
    int type;
    int x, y;       /* абсолютные экранные координаты (для POINTER_*) */
    int pressed;    /* 1, если указатель сейчас прижат (для MOVE)      */
    int key;        /* ASCII (для HAL_EV_KEY)                          */
} hal_input_event_t;

void hal_input_init(void);

/* Неблокирующий опрос: 1 и заполненный ev, если событие есть, иначе 0.
 * Вызывать в главном цикле, пока не вернёт 0 — за одну итерацию цикла
 * может накопиться несколько событий (например, палец быстро ведут). */
int hal_input_poll(hal_input_event_t *ev);

/* Сообщить бэкенду текущий размер экрана: тачскрин отдаёт координаты в
 * своей собственной сетке (у virtio-tablet это 0..32767), их надо
 * масштабировать в пиксели; PS/2-мыши нужны границы для клампа курсора.
 * Вызывать после hal_gfx_init() и после каждой смены разрешения. */
void hal_input_set_screen(int w, int h);

/* Есть ли у платформы физический указатель, который надо рисовать.
 * 1 = мышь (нужен курсор-стрелка), 0 = тачскрин (курсор не рисуем —
 * на телефоне стрелка мыши посреди экрана выглядит абсурдно). */
int hal_input_has_cursor(void);

/* Текущее положение указателя — для отрисовки курсора на x86. */
void hal_input_pointer_pos(int *x, int *y);

/* Нашлось ли хоть одно устройство ввода. На новом железе ответ вполне может
 * быть отрицательным: тачскрин висит на I2C и требует своего драйвера, а
 * последовательный порт без отладочного кабеля недоступен физически.
 * Оболочка по этому признаку решает, с какого экрана начинать: управлять
 * ей всё равно нечем, и полезнее сразу показать сведения о системе. */
int hal_input_available(void);

#endif
